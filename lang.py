def t(key: str) -> str:
    """Devuelve la traducción de la clave o la propia clave si no hay traducción."""
    return I18N.get(LANG, {}).get(key, key)


def set_language(lang_code: str):
    """Cambia el idioma global usado por la función `t`.
    No valida la existencia del idioma; simplemente asigna la variable.
    """
    global LANG
    LANG = lang_code
